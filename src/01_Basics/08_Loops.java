public class Loops {
    public static void main(String[] args) {

        // ============================================================
        // 1. for Loop
        // ============================================================

        for (int i = 1; i <= 5; i++) {
            System.out.println("for loop: " + i);
        }


        // ============================================================
        // 2. while Loop
        // ============================================================

        int i = 1;

        while (i <= 5) {
            System.out.println("while loop: " + i);
            i++;
        }


        // ============================================================
        // 3. do-while Loop
        // ============================================================

        int j = 1;

        do {
            System.out.println("do-while loop: " + j);
            j++;
        } while (j <= 5);


        // ============================================================
        // 4. Reverse Loop
        // ============================================================

        for (int k = 5; k >= 1; k--) {
            System.out.println("Reverse: " + k);
        }


        // ============================================================
        // 5. Print Even Numbers
        // ============================================================

        for (int n = 1; n <= 10; n++) {

            if (n % 2 == 0) {
                System.out.println("Even: " + n);
            }
        }


        // ============================================================
        // 6. Sum of Numbers
        // ============================================================

        int sum = 0;

        for (int n = 1; n <= 5; n++) {
            sum = sum + n;
        }

        System.out.println("Sum = " + sum);


        // ============================================================
        // 7. Nested Loops
        // ============================================================

        for (int row = 1; row <= 3; row++) {

            for (int col = 1; col <= 3; col++) {
                System.out.print("* ");
            }

            System.out.println();
        }


        // ============================================================
        // 8. Multiplication Table
        // ============================================================

        int number = 5;

        for (int x = 1; x <= 10; x++) {
            System.out.println(number + " x " + x + " = " + (number * x));
        }
    }
}